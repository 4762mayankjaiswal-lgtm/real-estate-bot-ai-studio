// Helper to create tomorrow at a specific hour in local/ISO format
function getUpcomingSlotIso(daysAhead: number, hour: number, minute = 0): string {
  const d = new Date(Date.now() + daysAhead * 86400000);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

